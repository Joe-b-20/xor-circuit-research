"""Verilog for a design: RTL (one assign per gate), the reference function (spec) and a testbench.

All modules have the ports ``input [n-1:0] x`` and ``output [m-1:0] y`` (bus values = function
values, see design.py).  The RTL module is ``dut``, the reference ``spec``.

Gates with a constant operand are written as what they compute: NIST writes NOT as
``XNOR t a 0``, which becomes ``~a`` (one inverter, as NIST counts it); a gate that computes a
copy of its operand becomes a wire alias.  Nothing else is simplified: every other gate of the
file is one Verilog operator, so the structure-preserving flow maps it to one cell.
"""
from __future__ import annotations

import random


def wire(name):
    return 'n_' + name


def simplified_gates(d):
    """``(op, out, args)`` with ops AND, XOR, XNOR, NOT, BUF, CONST0, CONST1 (constants folded)."""
    out = []
    for g in d.circuit.gates:
        op, args = g.op, list(g.args)
        consts = [a for a in args if a in ('0', '1')]
        if not consts:
            out.append((op, g.out, args))
            continue
        others = [a for a in args if a not in ('0', '1')]
        if op == 'NOT':
            out.append(('CONST1' if args[0] == '0' else 'CONST0', g.out, []))
        elif not others:          # both operands constant
            a, b = (int(v) for v in args)
            v = {'AND': a & b, 'XOR': a ^ b, 'XNOR': 1 ^ a ^ b}[op]
            out.append(('CONST%d' % v, g.out, []))
        else:
            c, a = int(consts[0]), others[0]
            if op == 'AND':
                out.append(('BUF', g.out, [a]) if c else ('CONST0', g.out, []))
            else:
                invert = (op == 'XNOR') ^ c
                out.append(('NOT' if invert else 'BUF', g.out, [a]))
    return out


def expected_cells(d):
    """Cell counts the structure-preserving mapping must produce (before output buffers)."""
    counts = {}
    for op, _, _ in simplified_gates(d):
        if op in ('AND', 'XOR', 'XNOR', 'NOT'):
            counts[op] = counts.get(op, 0) + 1
    return counts


def rtl(d):
    n, m = d.n_in, d.n_out
    lines = ['// %s (%s), generated by hardware/hwbench from %s' % (d.name, d.origin, d.path.name),
             '// sha256 of the circuit file: %s' % d.sha256,
             'module dut (input wire [%d:0] x, output wire [%d:0] y);' % (n - 1, m - 1)]
    # Signals are referred to by what drives them: an input is x[k]; a gate whose output is a
    # circuit output drives that port bit directly (no alias wire, so synthesis needs no buffer
    # between a wire and the port); other gates drive wires n_<name>; a copy is an alias.
    ref = {w: 'x[%d]' % d.in_bit[i] for i, w in enumerate(d.circuit.inputs)}
    port_of = {}
    for i, w in enumerate(d.circuit.outputs):
        port_of.setdefault(w, d.out_bit[i])
    driven = set()
    sym = {'AND': '&', 'XOR': '^', 'XNOR': '~^'}
    for op, o, a in simplified_gates(d):
        if op in sym:
            e = '%s %s %s' % (ref[a[0]], sym[op], ref[a[1]])
        elif op == 'NOT':
            e = '~%s' % ref[a[0]]
        elif op == 'BUF':
            if o not in port_of:
                ref[o] = ref[a[0]]
                continue
            e = ref[a[0]]
        else:
            e = "1'b%s" % op[-1]
        if o in port_of:
            ref[o] = 'y[%d]' % port_of[o]
            driven.add(port_of[o])
            lines.append('  assign %s = %s;  // %s' % (ref[o], e, o))
        else:
            ref[o] = wire(o)
            lines.append('  wire %s = %s;' % (ref[o], e))
    for i, w in enumerate(d.circuit.outputs):
        if d.out_bit[i] not in driven:       # an output that is an input, or a repeated output
            lines.append('  assign y[%d] = %s;  // %s' % (d.out_bit[i], ref[w], w))
    lines.append('endmodule')
    return '\n'.join(lines) + '\n'


def spec(d):
    """The reference function: a case table (S-boxes) or matrix rows (linear maps)."""
    n, m = d.n_in, d.n_out
    lines = ['// reference function %s, generated by hardware/hwbench (not from the circuit)' % d.function]
    if d.kind == 'boolean':
        lines += ['module spec (input wire [%d:0] x, output reg [%d:0] y);' % (n - 1, m - 1),
                  '  always @* begin', "    y = %d'h0;" % m, '    case (x)']
        hx, hy = (n + 3) // 4, (m + 3) // 4
        for x in range(1 << n):
            lines.append("      %d'h%0*x: y = %d'h%0*x;" % (n, hx, x, m, hy, d.table[x]))
        lines += ['    endcase', '  end', 'endmodule']          # full case: every x is listed
    else:
        lines.append('module spec (input wire [%d:0] x, output wire [%d:0] y);' % (n - 1, m - 1))
        for i, (r, c) in enumerate(zip(d.rows, d.consts)):
            e = "^(x & %d'h%x)" % (n, r)
            lines.append('  assign y[%d] = %s%s;' % (i, '~' if c else '', e))
        lines.append('endmodule')
    return '\n'.join(lines) + '\n'


def vectors(d, n_random=65536, seed=1):
    """Test inputs: all 2^n for n <= 16, else 0, the unit vectors, all-ones and random ones."""
    n = d.n_in
    if n <= 16:
        return list(range(1 << n))
    rng = random.Random(seed)
    xs = [0, (1 << n) - 1] + [1 << j for j in range(n)]
    xs += [rng.getrandbits(n) for _ in range(n_random)]
    return xs


def testbench(d, count):
    n, m = d.n_in, d.n_out
    return '\n'.join([
        '`timescale 1ns/1ps',
        'module tb;',
        '  reg  [%d:0] x;' % (n - 1),
        '  wire [%d:0] y;' % (m - 1),
        '  reg  [%d:0] vx [0:%d];' % (n - 1, count - 1),
        '  reg  [%d:0] vy [0:%d];' % (m - 1, count - 1),
        '  integer i, errors;',
        '  dut u (.x(x), .y(y));',
        '  initial begin',
        '    $readmemh("vec_x.hex", vx);',
        '    $readmemh("vec_y.hex", vy);',
        '    errors = 0;',
        '    for (i = 0; i < %d; i = i + 1) begin' % count,
        '      x = vx[i]; #1;',
        '      if (y !== vy[i]) begin',
        '        errors = errors + 1;',
        '        if (errors < 5) $display("MISMATCH x=%h y=%h expected=%h", x, y, vy[i]);',
        '      end',
        '    end',
        '    $display("CHECKED %0d ERRORS %0d", ' + str(count) + ', errors);',
        '    $finish;',
        '  end',
        'endmodule', ''])


def vector_files(d, xs):
    hx, hy = (d.n_in + 3) // 4, (d.n_out + 3) // 4
    return ('\n'.join('%0*x' % (hx, x) for x in xs) + '\n',
            '\n'.join('%0*x' % (hy, d.value(x)) for x in xs) + '\n')
