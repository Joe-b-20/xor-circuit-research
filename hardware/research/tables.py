#!/usr/bin/env python3
"""Markdown tables for the report from results/analysis.json (-> results/TABLES.md).

    python3 hardware/research/tables.py
"""
from __future__ import annotations

import collections
import json
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
RES = HERE / 'results'
LIB = {'nangate45': 'Nangate45', 'sky130hd': 'SKY130HD'}
FN = {'aes-sbox': 'S-box', 'aes-invsbox': 'inv S-box', 'aes-sbox-sel': 'sel S-box',
      'aes-mixcolumns': 'MixColumns', 'aes-invmixcolumns': 'InvMixColumns'}
FLOWS = ('preserve', 'free', 'free-area')
MEAS = ('area', 'delay', 'adp', 'power')
FUNCS = ('aes-sbox', 'aes-invsbox', 'aes-sbox-sel', 'aes-mixcolumns', 'aes-invmixcolumns')


def pct(x):
    return '—' if x is None else '%.1f%%' % (100 * x)


def short(c):
    return c.split('--', 1)[1] if '--' in c else c


def main():
    a = json.loads((RES / 'analysis.json').read_text())
    md = ['# Tables (generated by tables.py from analysis.json)', '',
          '%d circuits, %d (circuit, library, flow) rows after removing %d duplicates.' % (
              a['circuits'], a['rows'], len(a['duplicates_left_out'])), '']
    # noise
    md += ['## Noise: seed-to-seed coefficient of variation (median over seeded circuits)', '',
           '| Seeds | Library | Flow | n | area | delay | ADP | power |', '|---|---|---|---:|---:|---:|---:|---:|']
    for kind in ('pnr', 'synth'):
        for p in LIB:
            for f in FLOWS:
                cells = [a['noise'].get('%s|%s|%s|%s' % (kind, p, f, m)) for m in MEAS]
                if not any(cells):
                    continue
                n = max(c['n'] for c in cells if c)
                md.append('| %s | %s | %s | %d | %s |' % (kind, LIB[p], f, n, ' | '.join(
                    pct(c['median_cv']) if c else '—' for c in cells)))
    md.append('')
    # iso
    md += ['## Same-metric groups: relative range (max-min)/median of each measure', '',
           'Groups beyond noise: range above the 95% quantile of the range of n noise-only copies.', '',
           '| Library | Flow | groups | area: median range | beyond | delay: median | beyond | ADP: median | beyond | power: median | beyond |',
           '|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|']
    for p in LIB:
        for f in FLOWS:
            cells = []
            n = 0
            for m in MEAS:
                v = a['iso'].get('%s|%s|%s' % (p, f, m))
                if not v:
                    cells += ['—', '—']
                    continue
                n = v['groups']
                cells += [pct(v['median_rel_range']), '%d/%d' % (v['beyond_noise'], v['with_threshold'])]
            md.append('| %s | %s | %d | %s |' % (LIB[p], f, n, ' | '.join(cells)))
    md.append('')
    # pooled inversion shares
    if a.get('inversion_shares'):
        md += ['## Dominance inversions beyond noise, pooled over functions', '',
               'Among dominated pairs whose physical difference is beyond noise: the share where the '
               'logically worse circuit is better, and how often the file score also puts it first.', '',
               '| Circuits | Library | Flow | measure | pairs beyond noise | worse is better | score agrees |',
               '|---|---|---|---|---:|---:|---:|']
        for k, v in sorted(a['inversion_shares'].items()):
            sub, p, f, m = k.split('|')
            md.append('| %s | %s | %s | %s | %d | %s | %s |' % (
                sub, LIB[p], f, m, v['beyond_noise_pairs'], pct(v['share']), pct(v['score_agrees'])))
        md.append('')
    # inversions
    md += ['## Dominance inversions: the logically worse circuit (dominated in A, AD, G, GD) is physically better', '',
           'Per function: share of dominated pairs where the worse circuit wins / wins beyond noise.', '']
    for m in MEAS:
        md += ['### %s' % m, '', '| Function | ' + ' | '.join('%s %s' % (LIB[p], f) for p in LIB for f in FLOWS) + ' |',
               '|---|' + '---:|' * 6]
        for fn in FUNCS:
            cells = []
            for p in LIB:
                for f in FLOWS:
                    v = a['inversions'].get('%s|%s|%s|%s' % (fn, p, f, m))
                    if not v or not v['pairs']:
                        cells.append('—')
                        continue
                    sig = v['inverted_beyond_noise']
                    cells.append('%s / %s (%d pairs)' % (pct(v['inverted'] / v['pairs']),
                                                       pct(sig / v['pairs']) if v['threshold'] is not None else '?',
                                                       v['pairs']))
            md.append('| %s | %s |' % (FN[fn], ' | '.join(cells)))
        md.append('')
    # synthesis identity and agreement
    md += ['## Synthesis: same-metric pairs mapped to identical netlists', '',
           '| Library | Flow | pairs | identical |', '|---|---|---:|---:|']
    for k, v in sorted(a['synthesis_identical'].items()):
        _, p, f = k.split('|')
        md.append('| %s | %s | %d | %d |' % (LIB[p], f, v['same_metric_pairs'], v['identical']))
    md += ['', '## Within same-metric groups: does the preserve-flow ranking survive free synthesis? (mean Spearman)', '',
           '| Comparison | groups | mean rho | median rho |', '|---|---:|---:|---:|']
    for k, v in sorted(a['within_group_agreement'].items()):
        md.append('| %s | %d | %.2f | %.2f |' % (k, v['groups'], v['mean_rho'], v['median_rho']))
    md += ['', '## Rank agreement of routed delay between configurations (Spearman, all circuits of a function)', '']
    cfgs = ['%s/%s' % (p, f) for p in LIB for f in FLOWS]
    for m in ('delay', 'power', 'area'):
        md += ['### %s' % m, '', '| Function | ' + ' | '.join((
            'N-pres~S-pres', 'N-pres~N-free', 'N-pres~N-farea', 'N-free~S-free', 'N-farea~S-farea')) + ' |',
            '|---|---:|---:|---:|---:|---:|']
        pairs = [('nangate45/preserve', 'sky130hd/preserve'), ('nangate45/preserve', 'nangate45/free'),
                 ('nangate45/preserve', 'nangate45/free-area'), ('nangate45/free', 'sky130hd/free'),
                 ('nangate45/free-area', 'sky130hd/free-area')]
        for fn in FUNCS:
            mat = a['rank_agreement'].get('%s|%s' % (fn, m), {})
            cells = []
            for x, y in pairs:
                v = mat.get('%s~%s' % (x, y), mat.get('%s~%s' % (y, x)))
                cells.append('%.2f' % v if v is not None else '—')
            md.append('| %s | %s |' % (FN[fn], ' | '.join(cells)))
        md.append('')
    # prediction
    md += ['## Held-out prediction (test half; iso keys held out whole)', '',
           'Spearman over the test circuits of the function / mean Spearman within same-metric test groups / '
           'pair accuracy within groups on pairs beyond noise (ties count 1/2).', '']
    for m in ('delay', 'power', 'adp', 'area'):
        md += ['### %s' % m, '', '| Library | Flow | Function | abstract | physical (zero-fit) | ridge |', '|---|---|---|---|---|---|']
        for p in LIB:
            for f in FLOWS:
                for fn in FUNCS:
                    v = a['predict'].get('%s|%s|%s|%s' % (p, f, m, fn))
                    if not v:
                        continue

                    def q(x):
                        s = '%.2f' % x['spearman'] if x['spearman'] is not None else '—'
                        w = '%.2f' % x['within_group_rho'] if x.get('within_group_rho') is not None else '—'
                        pa = '%.2f (%d)' % (x['pair_accuracy_beyond_noise'], x['pairs_beyond_noise']) \
                            if x.get('pair_accuracy_beyond_noise') is not None else '—'
                        return '%s / %s / %s' % (s, w, pa)
                    md.append('| %s | %s | %s | %s | %s | %s |' % (LIB[p], f, FN[fn], q(v['abstract']),
                                                                  q(v['physical_zero_fit']), q(v['ridge'])))
        md.append('')
    md += ['### Leave one function out (ridge trained on the other four), Spearman / within-group', '',
           '| Library | Flow | measure | ' + ' | '.join(FN[f] for f in FUNCS) + ' |', '|---|---|---|' + '---|' * 5]
    for p in LIB:
        for f in FLOWS:
            for m in ('delay', 'power'):
                cells = []
                for fn in FUNCS:
                    v = a['predict'].get('lofo|%s|%s|%s|%s' % (p, f, m, fn))
                    if not v:
                        cells.append('—')
                        continue
                    r = v['ridge']
                    cells.append('%.2f / %s' % (r['spearman'], '%.2f' % r['within_group_rho']
                                                if r.get('within_group_rho') is not None else '—'))
                md.append('| %s | %s | %s | %s |' % (LIB[p], f, m, ' | '.join(cells)))
    md.append('')
    # within-group predictors
    if a.get('explain'):
        md += ['## What tracks each measure within same-metric groups (mean within-group Spearman)', '',
               'f_* from the circuit file; cells, m_* (mapped netlist), wire, delay_synth are measured. '
               'Only |rho| >= 0.3 in at least one configuration shown.', '']
        for m in ('delay', 'power'):
            feats = sorted({k for v in a['explain'].values() for k in v})
            keep = [ft for ft in feats if any(abs(a['explain'].get('%s|%s|%s' % (p, f, m), {}).get(ft, {}).get('mean_rho', 0)) >= 0.3
                                               for p in LIB for f in FLOWS)]
            md += ['### %s' % m, '', '| feature | ' + ' | '.join('%s %s' % (LIB[p][:4], f) for p in LIB for f in FLOWS) + ' |',
                   '|---|' + '---:|' * 6]
            for ft in keep:
                cells = []
                for p in LIB:
                    for f in FLOWS:
                        v = a['explain'].get('%s|%s|%s' % (p, f, m), {}).get(ft)
                        cells.append('%+.2f' % v['mean_rho'] if v else '—')
                md.append('| %s | %s |' % (ft, ' | '.join(cells)))
            md.append('')
    # screen
    if a.get('screen'):
        md += ['## Prospective screen: score top 10 vs random 10 vs bottom 10 per pool', '',
               'Median of each pick; change of the top median against the random median; one-sided '
               'Mann-Whitney p (top < random), Holm-corrected over all rows.', '',
               '| Pool | Library | Flow | measure | top | random | bottom | top vs random | p (Holm) |',
               '|---|---|---|---|---:|---:|---:|---:|---:|']
        for s in a['screen']:
            if s['measure'] not in ('delay', 'power', 'adp'):
                continue
            md.append('| %s %s | %s | %s | %s | %.4g | %.4g | %.4g | %+.1f%% | %.3g |' % (
                FN[s['function']], s['key'], LIB[s['platform']], s['flow'], s['measure'],
                s['median']['top'], s['median']['random'], s['median']['bottom'],
                100 * s['top_vs_random_median_change'], s['p_top_lt_random_holm']))
        md.append('')
    # largest inversions
    md += ['## Largest apparent dominance inversions (base run, before seeds)', '',
           '| Function | Library | Flow | measure | worse logically (wins) | better logically | gain |',
           '|---|---|---|---|---|---|---:|']
    tops = sorted(a['inversions_top'], key=lambda t: -t['gain'])
    seen = collections.Counter()
    for t in tops:
        k = (t['function'], t['measure'])
        if seen[k] >= 2 or t['measure'] == 'area' and t['flow'] == 'preserve':
            continue
        seen[k] += 1
        md.append('| %s | %s | %s | %s | %s (%s) | %s (%s) | %.1f%% |' % (
            FN[t['function']], LIB[t['platform']], t['flow'], t['measure'], short(t['worse_logically']),
            t['key_worse'], short(t['better_logically']), t['key_better'], 100 * t['gain']))
    md.append('')
    (RES / 'TABLES.md').write_text('\n'.join(md) + '\n')
    print('wrote', RES / 'TABLES.md')


if __name__ == '__main__':
    main()
