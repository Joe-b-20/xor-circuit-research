"""Search for rotation-symmetric circuits of Q_4 (rotation model, m = 4) with SAT.
Symmetry group generated by rho = shift of blocks by STEP (STEP = 1: order 4; STEP = 2: order 2).
A symmetric circuit with R rounds: round k has a base gate v_k = x + y (x, y = inputs or
rho^r(v_k') with k' < k), and its p rotated copies rho^r(v_k), r = 0..p-1, are gates too
(p*R gates in all; rotated copies are valid because rho^r of earlier signals are available).
Outputs: every output orbit representative must be rho^r(v_k) for some k, r.
Usage: python3 q4_sym.py STEP R"""
import sys
import time
from itertools import count
from pysat.solvers import Solver

m = int(sys.argv[3]) if len(sys.argv) > 3 else 4
STEP, R = int(sys.argv[1]), int(sys.argv[2])
SAVE = sys.argv[4] if len(sys.argv) > 4 else None
p = m // STEP
nb = 4 * m


def rot_bits(r):
    """permutation of bit positions for rho^r"""
    return [4 * ((i // 4 + r * STEP) % m) + i % 4 for i in range(nb)]


def rot_val(x, r):
    perm = rot_bits(r)
    return sum(1 << perm[i] for i in range(nb) if (x >> i) & 1)


def out(c, j):
    E = sum(1 << (4 * j + (c + k) % 4) for k in (1, 2, 3))
    s = (1 << (4 * ((j - 1) % m) + c % 4)) | (1 << (4 * ((j - 1) % m) + (c + 1) % 4))
    return E | s


reps = [out(c, j) for j in range(STEP) for c in range(4)]
ctr = count(1)
nv = lambda: next(ctr)
cl = []
v = [[nv() for _ in range(nb)] for _ in range(R)]
selinfo = []
for k in range(R):
    ops = []
    for side in range(2):
        w = [nv() for _ in range(nb)]
        opts = []
        for i in range(nb):
            s = nv()
            opts.append(("in", i, s))
            for b in range(nb):
                cl.append([-s, w[b] if b == i else -w[b]])
        for k2 in range(k):
            for r in range(p):
                s = nv()
                opts.append(("g", (k2, r), s))
                perm = rot_bits(r)  # bit b of rho^r(v) = bit perm^-1(b) of v
                inv = [0] * nb
                for i in range(nb):
                    inv[perm[i]] = i
                for b in range(nb):
                    src = v[k2][inv[b]]
                    cl.append([-s, -w[b], src])
                    cl.append([-s, w[b], -src])
        cl.append([o[2] for o in opts])
        ops.append((w, opts))
    selinfo.append(ops)
    (w0, _), (w1, _) = ops
    for b in range(nb):
        x, y, z = w0[b], w1[b], v[k][b]
        cl += [[-x, -y, -z], [x, y, -z], [x, -y, z], [-x, y, z]]
    cl.append(v[k][:])  # nonzero (sound: a zero gate is never needed)
for o in reps:
    lits = []
    for k in range(R):
        for r in range(p):
            t = rot_val(o, -r % p if True else 0)
            # need rho^r(v_k) == o  <=>  v_k == rho^(-r)(o)
            t = rot_val(o, (p - r) % p)
            y = nv()
            lits.append(y)
            for b in range(nb):
                cl.append([-y, v[k][b] if (t >> b) & 1 else -v[k][b]])
    cl.append(lits)
t0 = time.time()
with Solver(name="cadical153", bootstrap_with=cl) as S:
    res = S.solve()
    print("STEP=%d R=%d gates=%d result=%s time=%.1fs" % (STEP, R, p * R, "SAT" if res else "UNSAT", time.time() - t0),
          flush=True)
    if res:
        mod = set(l for l in S.get_model() if l > 0)
        vals = [sum(1 << b for b in range(nb) if v[k][b] in mod) for k in range(R)]
        # rebuild full circuit and verify
        sig = [1 << i for i in range(nb)]
        index = {}
        gates = []
        for k in range(R):
            chosen = []
            for side in range(2):
                w, opts = selinfo[k][side]
                o = next(o for o in opts if o[2] in mod)
                chosen.append(o)
            for r in range(p):
                def operand(o):
                    if o[0] == "in":
                        return rot_val(1 << o[1], r)
                    k2, r2 = o[1]
                    return rot_val(vals[k2], (r2 + r) % p)
                a, b = operand(chosen[0]), operand(chosen[1])
                assert a in sig and b in sig, "operand not available"
                gates.append((sig.index(a), sig.index(b)))
                sig.append(a ^ b)
        allout = [out(c, j) for j in range(m) for c in range(4)]
        assert all(o in sig for o in allout)
        print("verified full circuit with", len(sig) - nb, "gates")
        if SAVE:
            with open(SAVE, "w", newline="\n") as f:
                f.write("# symmetric circuit m=%d STEP=%d R=%d (reviewer)\n%d %d\n" % (m, STEP, R, nb, len(gates)))
                for a, b in gates:
                    f.write("%d %d\n" % (a, b))
