"""Static invariants of a double map D_T (no search).

usage: python3 geom.py "1|02|1"          (rows of T as lists of column indices, '-' = zero row)
       python3 geom.py m2                (the half-size MixColumns map, m = 8)

Prints: the lines U_k = <w_k, t_k>, delta(T) = dim K / K_2 = 2m - rho_4 (boundary relations not generated by
weight-4 relations), the forest criterion (Theorem C), and for small m the valid partitions.
Vectors of W = <w_0..w_(m-1)> are m-bit masks.
"""
import itertools
import sys

import dmap


def rank(vecs):
    basis = []
    for v in vecs:
        for b in basis:
            v = min(v, v ^ b)
        if v:
            basis.append(v)
    return len(basis)


def lines(T):
    """U_k minus 0 as a tuple (w_k, t_k, t_k + w_k)."""
    T = dmap.zero_diag(T)
    return [(1 << k, T[k], T[k] | (1 << k)) for k in range(len(T))]


def delta(T):
    """dim K - dim K_2, where K = ker(sum_k U_k -> W) (external sum) and K_2 = span of its weight-2 words.

    Computed as (number of generators [k, d]) - rank(line relations and identifications) - m, i.e. the
    dimension of the universal space  U~ = <[d]@k : d in U_k> / (lines, [d]@j = [d]@k)  minus m.
    """
    m = len(T)
    L = lines(T)
    # coordinates: (k, i) for the three nonzero vectors of U_k -> index 3k + i
    rels = []
    for k in range(m):
        rels.append((1 << (3 * k)) | (1 << (3 * k + 1)) | (1 << (3 * k + 2)))
    for j in range(m):
        for k in range(j + 1, m):
            for a in range(3):
                for b in range(3):
                    if L[j][a] == L[k][b]:
                        rels.append((1 << (3 * j + a)) | (1 << (3 * k + b)))
    return 3 * m - rank(rels) - m


def delta_levels(T):
    """[delta_2, delta_3, ...]: delta_i = dim K - dim K_i, K_i = span of the words of K of weight <= i.

    K = {(d_k) : d_k in U_k, sum d_k = 0}; a word is stored as 2 bits per sheet (coefficients of w_k, t_k).
    Brute force over the 4^m tuples (m <= 8).
    """
    m = len(T)
    T = dmap.zero_diag(T)
    by_weight = {}
    for code in range(4 ** m):
        s = 0
        wt = 0
        c = code
        for k in range(m):
            a = c & 3
            c >>= 2
            if a:
                wt += 1
                if a & 1:
                    s ^= 1 << k
                if a & 2:
                    s ^= T[k]
        if s == 0 and wt:
            by_weight.setdefault(wt, []).append(code)
    out = []
    acc = []
    for i in range(2, m + 1):
        acc += by_weight.get(i, [])
        out.append(m - rank(acc))
    return out


def boundary(T):
    m = len(T)
    rows = dmap.dmap_rows(T)
    return [1 << i for i in range(2 * m)] + rows


def rho4(points):
    """Dimension of the span of the weight-4 zero-sum subsets of a list of distinct masks."""
    idx = {p: i for i, p in enumerate(points)}
    pairs = {}
    n = len(points)
    for i in range(n):
        for j in range(i + 1, n):
            pairs.setdefault(points[i] ^ points[j], []).append((i, j))
    rels = []
    for d, lst in pairs.items():
        i0, j0 = lst[0]
        for (i, j) in lst[1:]:
            rels.append((1 << i0) | (1 << j0) | (1 << i) | (1 << j))
    return rank(rels)


def forest_criterion(T):
    """Theorem C: is there a root set R and a map k with lambda_k(j) in {t_j, t_j + w_j} for all j,
    where lambda_j = w_j for roots and lambda_j = lambda_k(j) + w_j otherwise (acyclic)?

    Equivalent fixed-point search: grow the set of available producers.  Returns (True, witness) or (False, None).
    witness[j] = (entering label mask, producer mask).
    """
    m = len(T)
    T = dmap.zero_diag(T)
    # producer of sheet j: 0 -> w_j (root), 1 -> t_j + w_j (entered with t_j), 2 -> t_j (entered with t_j + w_j)
    for choice in itertools.product(range(3), repeat=m):
        lam = [(1 << j, T[j] | (1 << j), T[j])[choice[j]] for j in range(m)]
        avail = {lam[j] for j in range(m) if choice[j] == 0}
        entered = set()
        changed = True
        while changed:
            changed = False
            for j in range(m):
                if j in entered:
                    continue
                if choice[j] == 0:
                    ok = T[j] in avail or (T[j] | (1 << j)) in avail
                else:
                    ok = (lam[j] ^ (1 << j)) in avail
                if ok:
                    entered.add(j)
                    avail.add(lam[j])
                    changed = True
        if len(entered) == m:
            return True, {j: lam[j] for j in range(m)}
    return False, None


def m2_T():
    # (Tw)_0 = w_7, (Tw)_j = w_(j-1) for j = 2,5,6,7 and w_(j-1) + w_7 for j = 1,3,4
    T = []
    for j in range(8):
        r = 1 << ((j - 1) % 8)
        if j in (1, 3, 4):
            r |= 1 << 7
        T.append(r)
    return tuple(T)


def vstr(v, m):
    return "+".join(f"w{k}" for k in range(m) if (v >> k) & 1) or "0"


def main():
    arg = sys.argv[1]
    T = m2_T() if arg == "m2" else dmap.parse_t(arg)
    m = len(T)
    print("T =", dmap.tstr(T), " reduced:", dmap.reduced(T), " rank:", dmap.rank_f2(dmap.zero_diag(T)))
    for k, (w, t, tw) in enumerate(lines(T)):
        print(f"  U_{k}: {vstr(w, m)} | {vstr(t, m)} | {vstr(tw, m)}")
    B = boundary(T)
    r4 = rho4(B)
    print("rho_4 =", r4, " delta = 2m - rho_4 =", 2 * m - r4, " (code formula:", delta(T), ")",
          " delta(T^T) =", delta(dmap.transpose(T)))
    if m <= 8:
        print("delta_i for i = 2..m (dim K / K_i):", delta_levels(T), " transpose:", delta_levels(dmap.transpose(T)))
    ok, wit = forest_criterion(T)
    print("forest criterion (eps = 0 in the pair partition):", ok)
    if ok:
        for j in sorted(wit):
            print(f"   producer of sheet {j}: {vstr(wit[j], m)}")
    if m <= 5:
        vp = dmap.valid_partitions(T, min_blocks=m - 1)
        cnt = {}
        for p in vp:
            cnt[max(p) + 1] = cnt.get(max(p) + 1, 0) + 1
        print("valid partitions by number of blocks (>= m-1):", dict(sorted(cnt.items())))


if __name__ == "__main__":
    main()
