#!/usr/bin/env python3
"""Tables from bridge/profiles.json (+ lb76 survivors/keys, + mobile.json if present) -> bridge/tables.md"""
import json, statistics
from collections import Counter, defaultdict
from math import comb

OUT = '/home/joebachir20/xs-campaigns/2026-11-07-sprint/bridge'
LB76 = '/home/joebachir20/xs-campaigns/2026-11-07-sprint/lb76'

LNAME = {  # checker row name -> proof row
    'reverse EE budget': 'L4', 'missing pairs': 'L5', 'full missing incidence': 'L6', 'label rank capacity': 'L7',
    'full helper budget': 'L8', 'weighted label capacity': 'L9', 'even signal fanout': 'L10',
    'full helper incidence': 'L11', 'boundary R6 rank': 'L12', 'quotient rank capacity': 'L13',
    'quotient full capacity': 'L14', 'quotient excess capacity': 'L15', 'full excess overflow': 'L16',
    'quotient joint deficit': 'L17', 'quotient full strengthened': 'L18', 'dark repeated pairs': 'L19',
    'dark quotient rank': 'L20', 'unanchored required': 'L21', 'short boundary rank': 'L22',
    'six color packing': 'L23(q=6)', 'seven color packing': 'L23(q=7)',
    'fanout cap s<=3h+2F+y-32': 'Lemma 4.3', 'incidence 32<=2h+y+z+C(q,2)': '(4.4)',
    'helper degree >= 2 (any circuit)': 'deg>=2', 'q=z=0 never': 'Lemma 10.3', 'Mt q=0 => z>=8 (canonical only)': 'Lemma 10.3b'}

d = json.load(open(OUT + '/profiles.json'))
R = [r for r in d['results'] if 'error' not in r]
S88 = [r for r in R if r['tag'].startswith('sample:')]
K88 = [r for r in R if r['tag'].startswith('kste:')]
REPO = [r for r in R if r['tag'].startswith('repo:')]
L = []


def P(*a):
    L.append(' '.join(str(x) for x in a))


def dist(vals):
    vals = sorted(vals)
    if not vals:
        return '-'
    return '%d / %g / %d' % (vals[0], statistics.median(vals), vals[-1])


def hist(vals):
    c = Counter(vals)
    return ', '.join('%s:%d' % (k, c[k]) for k in sorted(c))


P('# Tables (generated by summarize.py)\n')
P('circuits analysed: %d sampled 88 (distinct mod byte rotation), %d kste 88, %d repo; failures: %s\n' % (
    len(S88), len(K88), len(REPO), d['failures']))

# ---------------------------------------------------------------- reconstruction dependence
P('## Reconstruction: dependence on the parent-pair choice\n')
multi = Counter(r['recon']['n_multi'] for r in S88 + K88)
P('values with more than one admissible lower-level pair (strict mode), histogram over circuits:', hist(r['recon']['n_multi'] for r in S88 + K88 + REPO))
P('even values with both an even-even and an odd-odd lower-level pair:', hist(r['recon']['even_both'] for r in S88 + K88 + REPO))
P('dead-signal repairs needed:', hist(r['recon']['repairs'] for r in S88 + K88 + REPO))
nvar = Counter()
diff = Counter()
loose_err = Counter()
loose_same = loose_diff = 0
for r in S88 + K88 + REPO:
    base = (r['two']['a'], r['two']['Y'], r['two']['q0'], r['two']['z0'], r['two']['F0'], r['two']['b'], r['two']['V'])
    for v in r['variants']:
        if 'error' in v:
            loose_err[(v['pol'], v['error'][:40])] += 1
            continue
        cur = (v['x'], v['y'], v['q'], v['z'], v['F'], v['xT'], v['yT'])
        nvar[v['pol']] += 1
        if cur != base:
            diff[v['pol']] += 1
P('variants evaluated (policy: count, of which profile (x,y,q,z,F,xT,yT) differs from the base reconstruction):',
  {p: (nvar[p], diff[p]) for p in nvar})
P('variant errors:', dict(loose_err))
for r in REPO:
    same = r['two'] == r['true_two']
    P('repo %s: reconstructed two-phase profile == true gate list profile: %s' % (r['tag'], same))
P()

# ---------------------------------------------------------------- scalar profile distributions
for name, grp in (('sampled 88', S88), ('kste 88', K88)):
    if not grp:
        continue
    P('## Scalar profile, %s (N=%d): min / median / max\n' % (name, len(grp)))
    P('| quantity | C (orientation M) | T(C) (orientation Mt) |')
    P('|---|---|---|')
    for qn, k0, k1 in (('x (a | b)', 'a', 'b'), ('y (Y | V)', 'Y', 'V'), ('h (h_e | h_o)', 'he', 'ho'), ('F', 'F0', 'F1'),
                       ('q', 'q0', 'q1'), ('z', 'z0', 'z1'), ('s=q+z', 's0', 's1')):
        P('| %s | %s | %s |' % (qn, dist(r['two'][k0] for r in grp), dist(r['two'][k1] for r in grp)))
    P('| budget a+b+2G-192 | %s | |' % dist(r['two']['budget'] for r in grp))
    P('| s_C + s_T(C) | %s | |' % dist(r['two']['s_sum'] for r in grp))
    P('| margin = s_C + s_T(C) - budget | %s | |' % dist(r['two']['margin'] for r in grp))
    P('| actual drift e(TTC)-e(C) | %s | |' % dist(r['two']['drift_actual'] for r in grp))
    P()
    P('histograms:')
    for k in ('a', 'b', 'Y', 'V', 'he', 'ho', 'F0', 'F1', 'q0', 'z0', 'q1', 'z1', 's0', 's1', 'margin', 'drift_actual'):
        P('- %s: %s' % (k, hist(r['two'][k] for r in grp)))
    P('- (a,b): %s' % hist((r['two']['a'], r['two']['b']) for r in grp))
    P('- (Y,V): %s' % hist((r['two']['Y'], r['two']['V']) for r in grp))
    P('- (s0,s1): %s' % hist((r['two']['s0'], r['two']['s1']) for r in grp))
    P('- y along the orbit C,T,TT,TTT,...: %s' % hist(tuple(r['two']['ys']) for r in grp))
    P('- e1 along the orbit: %s' % hist(tuple(r['two']['e1s']) for r in grp))
    P('- orbit period 2 after step 1 (y,x,s,e1 at steps 1..5 alternate): %s' % hist(
        all(r['two'][k][i] == r['two'][k][i + 2] for k in ('ys', 'xs', 'ss', 'e1s') for i in range(1, 4)) for r in grp))
    P()
    # helper types
    P('helper type counts (r,u,v), phase C (M) then T(C) (Mt), summed over the %d circuits:' % len(grp))
    for ph in (0, 1):
        tot = Counter()
        for r in grp:
            for t, c in r['orbit'][ph]['types'].items():
                tot[t] += c
        P('- phase %d: %s' % (ph, ', '.join('%s:%d' % (t, tot[t]) for t in sorted(tot, key=lambda s: tuple(map(int, s.split(',')))))))
        P('  n_r (helpers with r=0,1,2,3) min/median/max: ' + '; '.join(
            'r=%d: %s' % (rr, dist(r['orbit'][ph]['n_r'][rr] for r in grp)) for rr in range(4)))
        P('  helper fan-out histogram (summed): %s' % hist(k for r in grp for k, c in r['orbit'][ph]['helper_fanout'].items() for _ in range(c)))
    P()
    # weight-2 labels
    P('weight-2 (input-pair) even values, phase C: count %s; represented %s; all weight-2 values represented in every circuit: %s; B-B edges %s; even signals total %s; represented labels (=even - q) %s' % (
        dist(r['orbit'][0]['w2'] for r in grp), dist(r['orbit'][0]['w2_rep'] for r in grp),
        all(r['orbit'][0]['w2'] == r['orbit'][0]['w2_rep'] for r in grp),
        dist(r['orbit'][0]['bb_edges'] for r in grp), dist(r['orbit'][0]['n_even'] for r in grp),
        dist(r['orbit'][0]['n_even'] - r['orbit'][0]['q'] for r in grp)))
    P('phase T(C): weight-2 count %s; represented %s; B-B edges %s' % (
        dist(r['orbit'][1]['w2'] for r in grp), dist(r['orbit'][1]['w2_rep'] for r in grp), dist(r['orbit'][1]['bb_edges'] for r in grp)))
    P()

P('## Repo circuits\n')
for r in REPO:
    t = r['two']
    P('- %s: a=%d b=%d Y=%d V=%d h_e=%d h_o=%d F=(%d,%d) q=(%d,%d) z=(%d,%d) budget=%d s_sum=%d margin=%d drift=%d ys=%s' % (
        r['tag'], t['a'], t['b'], t['Y'], t['V'], t['he'], t['ho'], t['F0'], t['F1'], t['q0'], t['q1'], t['z0'], t['z1'],
        t['budget'], t['s_sum'], t['margin'], t['drift_actual'], t['ys']))
    P('  types C: %s' % r['orbit'][0]['types'])
    P('  types T: %s' % r['orbit'][1]['types'])
P()

# ---------------------------------------------------------------- rows
P('## Rows (L1)-(L23) and lemmas on the real circuits: slack distribution\n')
for name, grp in (('sampled 88', S88), ('kste 88', K88), ('repo', REPO)):
    if not grp:
        continue
    for ph, lab in ((0, 'phase C, orientation M'), (1, 'phase T(C), orientation Mt'), (2, 'phase T(T(C)), orientation M')):
        P('### %s, %s (N=%d)\n' % (name, lab, len(grp)))
        P('| row | proof name | min / median / max slack | #slack 0 | #slack 1 | #slack<0 |')
        P('|---|---|---|---|---|---|')
        rows = defaultdict(list)
        for r in grp:
            for rn, sl in r['orbit'][ph]['rows'].items():
                rows[rn].append(sl)
        for rn in sorted(rows, key=lambda n: (LNAME.get(n, 'zz'), n)):
            v = rows[rn]
            P('| %s | %s | %s | %d | %d | %d |' % (LNAME.get(rn, '?'), rn, dist(v), sum(1 for x in v if x == 0),
                                                sum(1 for x in v if x == 1), sum(1 for x in v if x < 0)))
        P()

# ---------------------------------------------------------------- survivors
P('## Comparison with the G=75 survivors (lb76/g75_survivors.json, g75_keys.json)\n')
sv = json.load(open(LB76 + '/g75_survivors.json'))['survivor_list']
kk = json.load(open(LB76 + '/g75_keys.json'))
P('survivors: %d; LP-feasible keys (h,y,F,q,z,ori): %d' % (len(sv), len(kk['feasible'])))
P()
P('| coordinate | real sampled 88 (N=%d) | 75 survivors (N=%d) |' % (len(S88), len(sv)))
P('|---|---|---|')
for lab, kr, ks in (('a', 'a', 'a'), ('b', 'b', 'b'), ('Y', 'Y', 'Y'), ('V', 'V', 'V'), ('h_e', 'he', 'he'), ('h_o', 'ho', 'ho')):
    P('| %s | %s | %s |' % (lab, dist(r['two'][kr] for r in S88), dist(s[ks] for s in sv)))
P('| budget | %s | %s |' % (dist(r['two']['budget'] for r in S88), dist(s['budget'] for s in sv)))
P('| k+l (survivor forced s) vs real s_C+s_T | %s | %s |' % (dist(r['two']['s_sum'] for r in S88), dist(s['k'] + s['ell'] for s in sv)))
P('| S_e (fan-out cap) vs real s_C | %s | %s |' % (dist(r['two']['s0'] for r in S88), dist(s['Se'] for s in sv)))
P('| S_o vs real s_T | %s | %s |' % (dist(r['two']['s1'] for r in S88), dist(s['So'] for s in sv)))
P()
P('survivor orientation of the even phase: %s; real circuits: the max-y phase is T(C) (Mt) in %d of %d, C (M) in %d, tie %d' % (
    hist(s['orientation'] for s in sv),
    sum(1 for r in S88 if r['two']['V'] > r['two']['Y']), len(S88),
    sum(1 for r in S88 if r['two']['V'] < r['two']['Y']), sum(1 for r in S88 if r['two']['V'] == r['two']['Y'])))
P('survivor (Y,V): %s' % hist((s['Y'], s['V']) for s in sv))
P('survivor h_e+h_o: %s ; real: %s' % (dist(s['he'] + s['ho'] for s in sv), dist(r['two']['he'] + r['two']['ho'] for r in S88)))
P('survivor Y+V: %s ; real: %s' % (dist(s['Y'] + s['V'] for s in sv), dist(r['two']['Y'] + r['two']['V'] for r in S88)))
P()
P('LP-feasible keys at 75, by orientation: q distribution, z distribution, y, h, F:')
for ori in ('M', 'Mt'):
    ks = [k for k in kk['feasible'] if k[5] == ori]
    # key layout: inspect
    P('- %s: N=%d; h %s; y %s; F %s; q %s; z %s; s %s' % (
        ori, len(ks), dist(k[0] for k in ks), dist(k[1] for k in ks), dist(k[2] for k in ks), dist(k[3] for k in ks), dist(k[4] for k in ks), dist(k[3] + k[4] for k in ks)))
    P('  q histogram: %s' % hist(k[3] for k in ks))
    P('  z histogram: %s' % hist(k[4] for k in ks))
    P('  F histogram: %s' % hist(k[2] for k in ks))
    rp = S88
    P('  real sampled 88 same orientation: q %s; z %s; F %s; h %s; y %s' % (
        hist(r['two']['q0' if ori == 'M' else 'q1'] for r in rp), hist(r['two']['z0' if ori == 'M' else 'z1'] for r in rp),
        hist(r['two']['F0' if ori == 'M' else 'F1'] for r in rp), hist(r['two']['he' if ori == 'M' else 'ho'] for r in rp),
        hist(r['two']['Y' if ori == 'M' else 'V'] for r in rp)))
P()
# real-circuit phase fan-out caps and (4.4) at their own (h,y,F)
P('real sampled 88, phase C: fan-out cap S=3h+2F+y-32 vs s: %s ; phase T: %s' % (
    dist(3 * r['two']['he'] + 2 * r['two']['F0'] + r['two']['Y'] - 32 - r['two']['s0'] for r in S88),
    dist(3 * r['two']['ho'] + 2 * r['two']['F1'] + r['two']['V'] - 32 - r['two']['s1'] for r in S88)))
P('real sampled 88, Lemma 8.2 cap: S_e <= 2b-a+G-96+V, S_o <= 2a-b+G-96+Y (slack vs actual s): %s ; %s' % (
    dist(2 * r['two']['b'] - r['two']['a'] + 88 - 96 + r['two']['V'] - r['two']['s0'] for r in S88),
    dist(2 * r['two']['a'] - r['two']['b'] + 88 - 96 + r['two']['Y'] - r['two']['s1'] for r in S88)))
P('real sampled 88, (4.4) slack 2h+y+z+C(q,2)-32: C %s ; T %s' % (
    dist(2 * r['two']['he'] + r['two']['Y'] + r['two']['z0'] + comb(r['two']['q0'], 2) - 32 for r in S88),
    dist(2 * r['two']['ho'] + r['two']['V'] + r['two']['z1'] + comb(r['two']['q1'], 2) - 32 for r in S88)))
P()

# ---------------------------------------------------------------- hypotheses
P('## Hypothesis (a): odd non-output helpers\n')
P('h(C) over sampled 88: %s ; h(T(C)): %s ; min over both phases: %s' % (
    dist(r['two']['he'] for r in S88), dist(r['two']['ho'] for r in S88), dist(min(r['two']['he'], r['two']['ho']) for r in S88)))
P('h over orbit steps 2..5 (canonical transposes): %s' % hist(x for r in S88 for x in r['two']['hs'][2:]))
P()
try:
    m = json.load(open(OUT + '/mobile.json'))['records']
    P('## Hypothesis (b): mobility of weight-2 values under neutral remove1 (N=%d)\n' % len(m))
    P('engine gate count == 88: %s; improving moves found: %s' % (hist(x['engine_gates'] for x in m), hist(x['n_down'] for x in m)))
    P('neutral moves per circuit: %s' % dist(x['n_neutral'] for x in m))
    P('weight-2 helpers per circuit: %s; of which mobile: %s; fraction mobile: %s' % (
        dist(x['n_w2'] for x in m), dist(x['n_w2_mobile'] for x in m), dist(round(100 * x['n_w2_mobile'] / max(1, x['n_w2'])) for x in m)))
    P('mobile helpers total: %s; mobile non-weight-2 helpers: %s' % (dist(x['n_mobile'] for x in m), dist(x['n_mobile_nonw2'] for x in m)))
    P('neutral moves exchanging only weight-2 values: %s of %s' % (dist(x['pure_w2_moves'] for x in m), dist(x['n_neutral'] for x in m)))
    P('weights of removed helpers (summed): %s' % hist(w for x in m for w, c in x['weight_hist_removed'] for _ in range(c)))
    P('weights of all helpers (summed): %s' % hist(w for x in m for w, c in x['weight_hist_helpers'] for _ in range(c)))
    P('seconds per fan: %s' % dist(round(x['seconds']) for x in m))
except FileNotFoundError:
    P('(mobile.json not present)')

open(OUT + '/tables.md', 'w').write('\n'.join(L) + '\n')
print('\n'.join(L))
